CREATE TABLE IF NOT EXISTS MEDICAO (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SENSOR_ID   VARCHAR(50)      NOT NULL,
    TIPO_SENSOR VARCHAR(30)      NOT NULL
        CHECK (TIPO_SENSOR IN ('TEMPERATURA', 'CARGA_TRANSFORMADOR', 'CONSUMO_ENERGIA')),
    VALOR       DOUBLE PRECISION NOT NULL,
    DATA_HORA   TIMESTAMP        NOT NULL
);
CREATE INDEX IF NOT EXISTS IDX_MEDICAO_SENSOR ON MEDICAO (SENSOR_ID);

CREATE TABLE IF NOT EXISTS ALERTA (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SENSOR_ID        VARCHAR(50)      NOT NULL,
    TIPO_SENSOR      VARCHAR(30)      NOT NULL
        CHECK (TIPO_SENSOR IN ('TEMPERATURA', 'CARGA_TRANSFORMADOR', 'CONSUMO_ENERGIA')),
    NIVEL            VARCHAR(10)      NOT NULL
        CHECK (NIVEL IN ('ATENCAO', 'ALERTA', 'CRITICO')),
    VALOR_PREVISTO   DOUBLE PRECISION NOT NULL,
    LIMITE_ESTOURADO DOUBLE PRECISION NOT NULL,
    ESTRATEGIA       VARCHAR(60)      NOT NULL,
    MENSAGEM         VARCHAR(600)     NOT NULL,
    DATA_HORA        TIMESTAMP        NOT NULL
);
CREATE INDEX IF NOT EXISTS IDX_ALERTA_SENSOR ON ALERTA (SENSOR_ID);